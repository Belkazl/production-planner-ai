const assert = require('node:assert/strict');
const { createHash } = require('node:crypto');
const fs = require('node:fs');
const { chromium } = require('playwright');
const BASE = (process.env.LANDING_URL || 'http://127.0.0.1:3000').replace(/\/$/, '');
const RELEASE = 'seo-2026-10-15-v1';
const request = (path, init = {}) => fetch(BASE + path, { ...init, signal: AbortSignal.timeout(20000) });
(async () => {
  const checks = [];
  const ok = (name) => { checks.push(name); console.log('PASS: ' + name); };
  const response = await request('/');
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('x-liftorbit-release'), RELEASE);
  const html = await response.text();
  assert.match(html, /<html lang="en">/);
  assert.match(html, /<title>Production Planning Software for Manufacturers \| LiftOrbit<\/title>/);
  assert.equal((html.match(/<h1\b/g) || []).length, 1);
  assert.equal((html.match(/rel="canonical"/g) || []).length, 1);
  assert.match(html, /rel="canonical" href="https:\/\/liftorbit\.app\/"/);
  assert.match(html, /name="robots" content="index, follow/);
  assert.match(html, /What is LiftOrbit\?/);
  assert.match(html, /Who is LiftOrbit designed for\?/);
  const description = html.match(/<meta name="description" content="([^"]*)"/)[1];
  assert(description.length >= 120 && description.length <= 170);
  assert(!/trial|credit card/i.test(description));
  ok('Initial HTML contains indexable English product content and truthful metadata');
  const jsonText = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1];
  const data = JSON.parse(jsonText);
  const software = data['@graph'].find((item) => item['@type'] === 'SoftwareApplication');
  assert.equal(software.name, 'LiftOrbit');
  assert.equal(software.url, 'https://liftorbit.app/');
  assert(software.featureList.length >= 6);
  assert(!software.offers && !software.aggregateRating && !software.review);
  const hash = createHash('sha256').update(jsonText).digest('base64');
  assert(response.headers.get('content-security-policy').includes("'sha256-" + hash + "'"));
  ok('Valid JSON-LD uses real product facts and matches CSP');
  const robotsResponse = await request('/robots.txt');
  assert.equal(robotsResponse.status, 200);
  assert.match(robotsResponse.headers.get('content-type'), /text\/plain/);
  const robots = await robotsResponse.text();
  assert.match(robots, /User-agent: \*\nAllow: \/\n/);
  assert(!/^Disallow:\s*\/$/m.test(robots));
  assert.match(robots, /Sitemap: https:\/\/liftorbit\.app\/sitemap.xml/);
  ok('robots.txt permits search and AI-search crawlers');
  const sitemapResponse = await request('/sitemap.xml');
  assert.equal(sitemapResponse.status, 200);
  assert.match(sitemapResponse.headers.get('content-type'), /application\/xml/);
  const sitemap = await sitemapResponse.text();
  assert.match(sitemap, /<loc>https:\/\/liftorbit\.app\/<\/loc>/);
  assert.equal((sitemap.match(/<loc>/g) || []).length, 1);
  assert(!sitemap.includes('app.liftorbit.app') && !sitemap.includes('/health'));
  ok('Sitemap includes only the public canonical landing page');
  const duplicate = await request('/index.html', { redirect: 'manual' });
  assert.equal(duplicate.status, 308);
  assert.equal(duplicate.headers.get('location'), '/');
  const missing = await request('/not-a-real-page-seo-check');
  assert.equal(missing.status, 404);
  assert.equal(missing.headers.get('x-robots-tag'), 'noindex');
  assert.equal((await request('/', { method: 'HEAD' })).status, 200);
  assert.equal((await request('/', { method: 'POST' })).status, 405);
  assert.equal((await request('/', { headers: { 'if-none-match': response.headers.get('etag') } })).status, 304);
  for (const path of ['/site.css?v=1', '/site.js?v=1', '/favicon.svg', '/health']) assert.equal((await request(path)).status, 200, path);
  ok('Canonical redirect, real 404, caching, HEAD and existing assets work');
  const browser = await chromium.launch({ headless: true });
  try {
    const noJs = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 1440, height: 1000 } });
    const plain = await noJs.newPage();
    await plain.goto(BASE + '/', { waitUntil: 'load' });
    assert.equal(await plain.locator('h1').count(), 1);
    assert((await plain.locator('.hero-lede').innerText()).includes('production planning software'));
    assert((await plain.locator('#faq').textContent()).includes('What is LiftOrbit?'));
    assert.equal(await plain.locator('script[type="application/ld+json"]').count(), 1);
    await noJs.close();
    ok('Product answers and metadata are present without JavaScript');
    for (const width of [1440, 375]) {
      const context = await browser.newContext({ viewport: { width, height: 1000 } });
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', (error) => errors.push(error.message));
      page.on('console', (message) => { if (message.type() === 'error' && /content security policy|refused to/i.test(message.text())) errors.push(message.text()); });
      await page.goto(BASE + '/', { waitUntil: 'networkidle' });
      assert.equal(await page.locator('h1').count(), 1);
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2));
      await page.locator('.hero-actions [data-trial-trigger]').click();
      assert.equal(await page.locator('#trial-dialog').evaluate((el) => el.open), true);
      assert.equal(await page.locator('.modal-continue').getAttribute('href'), 'https://app.liftorbit.app/');
      await page.locator('.modal-close').click();
      await page.locator('#faq details').first().locator('summary').click();
      assert.equal(await page.locator('#faq details').first().evaluate((el) => el.open), true);
      await page.screenshot({ path: 'liftorbit-seo-' + width + '.png', fullPage: true });
      assert.deepEqual(errors, []);
      await context.close();
    }
    ok('Desktop and mobile layouts, FAQ and registration-link dialog work without browser errors');
  } finally { await browser.close(); }
  fs.writeFileSync('liftorbit-seo-report.json', JSON.stringify({ base: BASE, release: RELEASE, checks, passed: checks.length }, null, 2));
  console.log('SEO_CHECKS_PASSED=' + checks.length);
})().catch((error) => { console.error(error); process.exit(1); });
