"use strict";
const assert=require("node:assert/strict");
const {createHash}=require("node:crypto");
const base=(process.env.LANDING_URL||"http://127.0.0.1:3000/").replace(/\/$/,"");
const get=async(path,opts)=>fetch(base+path,{redirect:"manual",...opts});
(async()=>{
 const page=await get("/");
 assert.equal(page.status,200);
 const html=await page.text();
 const title="Production Scheduling Software for Small Manufacturers | LiftOrbit";
 const description="LiftOrbit helps small manufacturers plan orders, machines, people, materials and changeovers with visual Gantt charts and production schedule optimization.";
 assert(html.includes("<title>"+title+"</title>"));
 assert(html.includes('name="description" content="'+description+'"'));
 assert(html.includes('rel="canonical" href="https://liftorbit.app/"'));
 assert(html.includes('name="robots" content="index, follow'));
 assert(html.includes('og:site_name'));
 assert(html.includes('name="twitter:card"'));
 assert(html.includes('LiftOrbit helps small manufacturers plan orders'));
 assert(!html.includes('name="description" content="Production planning made simpler'));
 assert.equal((html.match(/<h1\b/g)||[]).length,1);
 const schemas=[...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)].map(m=>m[1]);
 assert.equal(schemas.length,1);
 const schema=JSON.parse(schemas[0]);assert.equal(schema["@context"],"https://schema.org");
 const types=schema["@graph"].flatMap(x=>Array.isArray(x["@type"])?x["@type"]:[x["@type"]]);
 for(const type of ["WebSite","WebPage","Organization","SoftwareApplication","FAQPage"])assert(types.includes(type));
 const faq=schema["@graph"].find(x=>x["@type"]==="FAQPage");
 assert.equal(faq.mainEntity.length,9);
 for(const question of faq.mainEntity)assert(html.includes(question.name.replaceAll("&","&amp;"))||html.includes(question.name));
 const hash="'sha256-"+createHash("sha256").update(schemas[0],"utf8").digest("base64")+"'";
 assert(page.headers.get("content-security-policy").includes(hash),"CSP must permit exact JSON-LD without allowing unsafe inline script");
 const robots=await get("/robots.txt");assert.equal(robots.status,200);
 assert((await robots.text()).includes("Sitemap: https://liftorbit.app/sitemap.xml"));
 const sitemap=await get("/sitemap.xml");assert.equal(sitemap.status,200);
 assert((await sitemap.text()).includes("<loc>https://liftorbit.app/</loc>"));
 const llms=await get("/llms.txt");assert.equal(llms.status,200);assert((await llms.text()).includes("LiftOrbit"));
 const duplicate=await get("/index.html");assert.equal(duplicate.status,308);
 assert.equal(duplicate.headers.get("location"),"https://liftorbit.app/");
 const health=await get("/health");assert.equal(health.status,200);
 assert(health.headers.get("x-robots-tag").includes("noindex"));
 const missing=await get("/missing-seo-test");assert.equal(missing.status,404);
 assert(missing.headers.get("x-robots-tag").includes("noindex"));
 for(const path of ["/site.css","/site.js","/favicon.svg"])assert.equal((await get(path)).status,200);
 console.log("LIFTORBIT_SEO_PASS",JSON.stringify({url:base,title,faq:faq.mainEntity.length,jsonLd:true,csp:true,robots:true,sitemap:true,llms:true,canonicalRedirect:true,assets:true}));
})().catch(e=>{console.error(e);process.exit(1)});
